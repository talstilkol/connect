-- PostgreSQL contact organization and resumable import persistence.
-- This migration intentionally contains no seed or demonstration data.

CREATE TABLE contact_tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  name TEXT NOT NULL,
  normalized_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL
    DEFAULT date_trunc('milliseconds', CURRENT_TIMESTAMP),
  updated_at TIMESTAMPTZ NOT NULL
    DEFAULT date_trunc('milliseconds', CURRENT_TIMESTAMP),
  CONSTRAINT contact_tags_tenant_fk
    FOREIGN KEY (tenant_id)
    REFERENCES tenants (id)
    ON DELETE CASCADE,
  CONSTRAINT contact_tags_name_valid
    CHECK (
      length(btrim(name)) > 0
      AND name = btrim(name)
    ),
  CONSTRAINT contact_tags_normalized_name_valid
    CHECK (
      length(btrim(normalized_name)) > 0
      AND normalized_name = btrim(normalized_name)
    ),
  CONSTRAINT contact_tags_timestamps_valid
    CHECK (
      created_at = date_trunc('milliseconds', created_at)
      AND updated_at = date_trunc('milliseconds', updated_at)
      AND updated_at >= created_at
    ),
  CONSTRAINT contact_tags_tenant_id_uq
    UNIQUE (tenant_id, id),
  CONSTRAINT contact_tags_tenant_name_uq
    UNIQUE (tenant_id, normalized_name)
);

CREATE INDEX contact_tags_tenant_created_idx
  ON contact_tags (tenant_id, created_at);

